import { Thing } from '../../models/comic.models';
import { Shape } from '../stick-figure/stick-figure.features';

/**
 * How each object and background animal is drawn: a few plain shapes with a dark outline, so it
 * reads at a glance and looks the same every time. Each drawing sits in its own box (0,0 at the top
 * left, `width` by `height`), standing on the box's bottom edge. Animals face right.
 *
 * @param size how wide it is drawn on the ground, as a percentage of the panel's width
 */
export interface ThingArt {
  width: number;
  height: number;
  size: number;
  shapes: Shape[];
}

const INK = '#1b1b1f';
const WOOD = '#b07a43';
const WOOD_DARK = '#8a5a2b';
const PAPER = '#fdf6e3';
const GOLD = '#f2c230';
const RED = '#d9483b';
const BLUE = '#4f86c6';
const GREEN = '#5fa35a';
const GREY = '#a7a7a7';
const BROWN = '#9a6b45';
const WHITE = '#ffffff';
const PINK = '#f2a7b8';
const ORANGE = '#e8862f';

const p = (d: string, fill: string, strokeWidth = 2, stroke = INK): Shape => ({
  kind: 'path',
  name: 'thing',
  d,
  fill,
  stroke,
  strokeWidth,
});
const c = (cx: number, cy: number, r: number, fill: string, stroke = INK, strokeWidth = 2): Shape => ({
  kind: 'circle',
  name: 'thing',
  cx,
  cy,
  r,
  fill,
  stroke,
  strokeWidth,
});
const e = (cx: number, cy: number, rx: number, ry: number, fill: string, strokeWidth = 2): Shape => ({
  kind: 'ellipse',
  name: 'thing',
  cx,
  cy,
  rx,
  ry,
  fill,
  stroke: INK,
  strokeWidth,
});
const r = (x: number, y: number, width: number, height: number, fill: string, strokeWidth = 2): Shape => ({
  kind: 'rect',
  name: 'thing',
  x,
  y,
  width,
  height,
  fill,
  stroke: INK,
  strokeWidth,
});
/** A dot of ink, for eyes. */
const eye = (cx: number, cy: number, radius = 1.6): Shape => c(cx, cy, radius, INK, 'none', 0);
/** Plain lines, such as legs, with no fill. */
const line = (d: string, strokeWidth = 2.5): Shape => p(d, 'none', strokeWidth);

const art = (width: number, height: number, size: number, ...shapes: Shape[]): ThingArt => ({
  width,
  height,
  size,
  shapes,
});

/** Four straight legs under a body, for the four-legged animals. */
const legs = (x1: number, x2: number, top: number, bottom: number) =>
  line(
    `M${x1},${top} L${x1 - 2},${bottom} M${x1 + 6},${top} L${x1 + 6},${bottom} ` +
      `M${x2},${top} L${x2},${bottom} M${x2 + 6},${top} L${x2 + 8},${bottom}`,
  );

